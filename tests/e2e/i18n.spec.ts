import { expect, test } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { waitForVisualSettling } from "./visual-settling";

test("中英文即时切换、持久化，并保留未保存的模型表单", async ({ page }) => {
  await page.setViewportSize({ width: 1366, height: 900 });
  await page.goto("/settings");
  await page.getByLabel("语言", { exact: true }).selectOption("en");
  await expect(page.locator("html")).toHaveAttribute("lang", "en");
  await expect(page.getByRole("heading", { name: "Settings", exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "Knowledge base", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Add model service", exact: true }).click();
  await page.getByLabel("Model name", { exact: true }).fill("未保存的模型-name");
  await page.getByLabel("Language", { exact: true }).selectOption("zh-CN");
  await expect(page.getByLabel("模型名", { exact: true })).toHaveValue("未保存的模型-name");
  await page.getByLabel("语言", { exact: true }).selectOption("en");
  await expect(page.getByLabel("Model name", { exact: true })).toHaveValue("未保存的模型-name");
  await page.getByLabel("Model name", { exact: true }).fill("");
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await waitForVisualSettling(page);
  await page.screenshot({ path: "test-results/i18n-settings-desktop.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const audit = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(audit.violations.map(item => item.id)).toEqual([]);
  await page.reload();
  await expect(page.getByLabel("Language", { exact: true })).toHaveValue("en");
  await page.getByRole("link", { name: "New chat", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Ask the knowledge base" })).toBeVisible();
  await page.goto("/wiki");
  await expect(page.getByRole("heading", { name: "Knowledge base", exact: true })).toBeVisible();
  await page.goto("/settings");
  await page.setViewportSize({ width: 390, height: 844 });
  await waitForVisualSettling(page);
  await page.screenshot({ path: "test-results/i18n-settings-mobile.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Open navigation", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Navigation" })).toBeVisible();
  await page.getByRole("link", { name: "Knowledge base", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Knowledge base", exact: true })).toBeVisible();
  await page.goto("/settings");
  await page.getByLabel("Language", { exact: true }).selectOption("zh-CN");
  await expect(page.getByRole("heading", { name: "设置", exact: true })).toBeVisible();
});
